/**
 * Boot: generates all procedural textures (no binary assets in phase 1),
 * validates the full question/level data set, and wires the shared
 * managers into the scene registry. Invalid data stops the game with a
 * visible error instead of loading broken levels.
 */
import Phaser from 'phaser';
import { STATES, COLORS, WORLD, SLINGSHOT, PROJECTILE_TYPES, QUESTION_CARD } from '../config.js';
import { QuestionManager } from '../systems/QuestionManager.js';
import { LevelManager } from '../systems/LevelManager.js';
import { SaveManager } from '../systems/SaveManager.js';
import { AudioManager, audioPreloadList } from '../systems/AudioManager.js';
import { deviceInfo } from '../systems/Device.js';
import { BackgroundManager } from '../systems/BackgroundManager.js';
import { ensureSlingshotTexture } from '../systems/SlingshotRenderer.js';
import { ensureQuestionCardTexture } from '../systems/QuestionCard.js';
import { FEEDBACK_CARD } from '../systems/FeedbackCard.js';
import { preloadList, TOWER_ASSETS } from '../data/tower-assets.js';
import { birdPreloadList } from '../data/birds.js';
import { hudPreloadList, ensureHudArtFallback } from '../systems/HudArt.js';
import { pauseIconPreloadList } from '../systems/GameHUD.js';
import questionsData from '../data/questions.json';
import levelsData from '../data/levels.json';

/** Audio preload keys — for the loaderror filter above (Fix #22).
 * Music is NOT part of the boot batch (loaded by MenuScene instead). */
const AUDIO_KEYS = new Set(audioPreloadList({ includeMusic: false }).map((e) => e.key));

export class BootScene extends Phaser.Scene {
  constructor() {
    super('BootScene');
    this.state = STATES.BOOTING;
  }

  /**
   * Queue the official gameplay background, the supplied wooden slingshot
   * artwork and the tower sprite pack. A missing binary falls back to a
   * procedural texture with the same key (load error listener below), so
   * the game never breaks.
   */
  preload() {
    this.registry.set('device', deviceInfo());
    BackgroundManager.preload(this);

    this.load.image(
      SLINGSHOT.ART.KEY,
      (import.meta.env.BASE_URL || '/') + 'assets/images/slingshot/slingshot-wood.png'
    );

    const BASE = (import.meta.env.BASE_URL || '/') + 'assets/images/tower/';
    for (const { key, file } of preloadList()) {
      this.load.image(`tw-${key}`, BASE + file);
    }

    // Bird projectile artwork (Fix #6): six cartoon birds mapped onto the
    // existing projectile roster. If a bird PNG is unreachable, the
    // projectile factory falls back to the legacy procedural circle
    // textures of the same size ('proj-*' keys generated in
    // generateTextures), so gameplay never breaks (headless test envs).
    const BIRDBASE = (import.meta.env.BASE_URL || '/') + 'assets/images/birds/';
    for (const { key, file } of birdPreloadList()) {
      this.load.image(key, BIRDBASE + file);
    }

    // Fix #9 — the wooden parchment question card (supplied artwork,
    // transparency preserved). If unreachable (headless test env), the
    // QuestionCard system draws a procedural parchment banner under the
    // same key with identical layout ratios, so gameplay never breaks.
    this.load.image(
      QUESTION_CARD.TEXTURE,
      (import.meta.env.BASE_URL || '/') + 'assets/images/ui/question-card.png'
    );

    // Blank wooden parchment feedback card (correct/wrong answer panel).
    // The skin stays BLANK: header, badge, texts and button are drawn by
    // js/systems/FeedbackCard.js at runtime. Missing PNG → the component's
    // procedural parchment fallback (headless test environments).
    this.load.image(
      FEEDBACK_CARD.TEXTURE,
      (import.meta.env.BASE_URL || '/') + FEEDBACK_CARD.ART
    );

    // Supplied blank wooden HUD artwork (top bar): frames only — every
    // label, icon and counter is a separate game object drawn by GameHUD.
    // If a PNG is unreachable, a procedural stand-in with the SAME measured
    // geometry is generated under the same key so the HUD layout never
    // breaks (headless test environments).
    const HUDBASE = (import.meta.env.BASE_URL || '/') + 'assets/images/ui/hud/';
    for (const { key, file } of hudPreloadList()) {
      this.load.image(key, HUDBASE + file);
    }

    // Pause-menu icon artwork (restart arrow, home cottage): real PNGs
    // generated by scripts/build-pause-icons.mjs. If unreachable, GameHUD
    // falls back to its small procedural icons (headless environments).
    const PAUSEBASE = (import.meta.env.BASE_URL || '/') + 'assets/images/pause/';
    for (const { key, file } of pauseIconPreloadList()) {
      this.load.image(key, PAUSEBASE + file);
    }

    // Fix #22 — the complete original audio set (WAV: universally decoded
    // by every supported browser, generated by scripts/generate-audio.mjs).
    // A missing file only warns (the AudioManager cache-checks every play,
    // so gameplay never breaks on a missing asset).
    // PERF: the 2.2 MB looping music track is NOT part of this boot batch —
    // MenuScene.preload loads it while the menu is on screen, well before
    // the only gesture that can start it (the PLAY press).
    const AUDIOBASE = (import.meta.env.BASE_URL || '/') + 'assets/audio/';
    for (const { key, file } of audioPreloadList({ includeMusic: false })) {
      this.load.audio(key, AUDIOBASE + file);
    }

    this.load.on('loaderror', (file) => {
      if (AUDIO_KEYS.has(file.key)) {
        console.warn(`[Boot] audio asset missing (${file.key}) — sound disabled for that key`);
        return;
      }
      if (file.key === SLINGSHOT.ART.KEY) {
        // artwork unreachable (e.g. headless test env): draw a wooden Y with
        // identical anchor geometry so the slingshot still works
        console.warn(`[Boot] slingshot artwork missing — procedural fallback`);
        ensureSlingshotTexture(this);
        return;
      }
      if (file.key === QUESTION_CARD.TEXTURE) {
        console.warn(`[Boot] question-card artwork missing — procedural fallback`);
        ensureQuestionCardTexture(this);
        return;
      }
      if (file.key === FEEDBACK_CARD.TEXTURE) {
        // the FeedbackCard constructor generates its procedural parchment
        // the moment it finds the texture key absent — nothing to do here
        console.warn(`[Boot] feedback-card artwork missing — procedural fallback`);
        return;
      }
      if (file.key.startsWith('bird-')) {
        console.warn(`[Boot] bird artwork missing (${file.key}) — circle fallback`);
        return;
      }
      if (file.key.startsWith('hud-')) {
        console.warn(`[Boot] HUD artwork missing (${file.key}) — procedural fallback`);
        ensureHudArtFallback(this, file.key);
        return;
      }
      if (!file.src.includes('/tower/')) return;
      const key = file.key;
      console.warn(`[Boot] tower sprite missing (${key}) — procedural fallback`);
      this.generateFallbackTexture(key);
    });
  }

  create() {
    this.state = STATES.LOADING;
    this.generateTextures();

    try {
      const questionManager = new QuestionManager(questionsData);
      const levelManager = new LevelManager(levelsData, questionsData);
      const save = new SaveManager();
      save.load();
      // Fix #22 — the audio manager is created ONCE per game and kept in
      // the registry (survives every scene restart). attach() binds it to
      // this scene's sound manager + audio cache + the save settings; it
      // is idempotent, so nothing can ever double-attach.
      this.registry.set('save', save);
      const audio = new AudioManager();
      this.registry.set('audio', audio);
      audio.attach(this);
      this.registry.set('questions', questionManager);
      this.registry.set('levels', levelManager);
      this.registry.set('bootTime', this.time.now);

      if (levelManager.validation.warnings.length) {
        console.warn('[Boot] level warnings:\n  - ' + levelManager.validation.warnings.join('\n  - '));
      }
      this.state = STATES.MENU;
      this.scene.start('MenuScene');
    } catch (err) {
      console.error('[Boot] data validation failed:', err);
      this.cameras.main.setBackgroundColor('#2a2a2a');
      const lines = String(err.message).split('\n');
      this.add.text(40, 40, 'WORD BLAST — DATA ERROR\n\n' + lines.join('\n'), {
        fontFamily: 'monospace', fontSize: '16px', color: '#ff6b6b', wordWrap: { width: WORLD.WIDTH - 80 }
      }).setDepth(100);
    }
  }

  /* ------------------------------------------------------------------ */

  generateTextures() {
    const g = this.add.graphics();

    // blocks
    this.blockTexture(g, 'tex-wood', COLORS.WOOD, COLORS.WOOD_DARK);
    this.blockTexture(g, 'tex-glass', COLORS.GLASS, COLORS.GLASS_DARK, 0.75);
    this.blockTexture(g, 'tex-stone', COLORS.STONE, COLORS.STONE_DARK);
    // explosive barrel
    g.clear();
    g.fillStyle(COLORS.BOOM, 1);
    g.fillRect(0, 0, 64, 64);
    g.fillStyle(0xfdc500, 1);
    g.fillRect(0, 24, 64, 16);
    g.generateTexture('tex-boom', 64, 64);

    // answer target
    g.clear();
    g.fillStyle(COLORS.TARGET, 1);
    g.fillRoundedRect(0, 0, 128, 72, 12);
    g.lineStyle(4, 0x1d3557, 1);
    g.strokeRoundedRect(0, 0, 128, 72, 12);
    g.generateTexture('tex-target', 128, 72);

    // projectiles — FALLBACK circles only: the real projectiles use the
    // bird artwork ('bird-*', preloaded above); these keys remain for
    // environments where the PNGs could not be fetched (headless tests)
    for (const key of Object.keys(PROJECTILE_TYPES)) {
      this.circleTexture(g, `proj-${key}`, COLORS.PROJECTILES[key]);
    }
    this.circleTexture(g, 'proj-split-child', COLORS.PROJECTILES.split);

    // trajectory dot
    g.clear();
    g.fillStyle(0xffffff, 1);
    g.fillCircle(4, 4, 4);
    g.generateTexture('dot', 8, 8);

    // particle textures (EffectsSystem)
    g.clear();
    g.fillStyle(0xffffff, 1);
    g.fillCircle(12, 12, 12);
    g.generateTexture('p-dust', 24, 24);
    g.clear();
    g.fillStyle(0xffffff, 1);
    g.fillRect(0, 0, 10, 4);
    g.generateTexture('p-splinter', 10, 4);
    g.clear();
    g.fillStyle(0xffffff, 1);
    g.fillTriangle(0, 8, 4, 0, 8, 8);
    g.generateTexture('p-shard', 8, 8);
    g.clear();
    g.fillStyle(0xffffff, 1);
    g.fillCircle(10, 10, 10);
    g.generateTexture('p-puff', 20, 20);
    g.clear();
    g.fillStyle(0xffffff, 1);
    g.fillCircle(6, 6, 6);
    g.generateTexture('p-spark', 12, 12);

    // fragment textures (factory spawnFragments) — material chips
    this.blockTexture(g, 'frag-wood', COLORS.WOOD, COLORS.WOOD_DARK);
    this.blockTexture(g, 'frag-stone', COLORS.STONE, COLORS.STONE_DARK);
    this.blockTexture(g, 'frag-glass', COLORS.GLASS, COLORS.GLASS_DARK, 0.8);
    this.blockTexture(g, 'frag-boom', COLORS.BOOM, 0x8a3a24);

    g.destroy();
  }

  /** Procedural stand-in for a missing tower sprite (keeps the game up). */
  generateFallbackTexture(key) {
    if (this.textures.exists(key)) return;
    const g = this.add.graphics();
    const asset = preloadList().find((p) => `tw-${p.key}` === key);
    // Answer panels keep their TRUE size in the fallback so the physics
    // collider + display size match the real artwork exactly — headless
    // tests then exercise the same geometry as the browser.
    if (asset && asset.key.startsWith('answer_panel')) {
      // drawn at CONTENT dims (600×194 for XL etc.) so displaySizeFor's
      // trimmed-canvas path maps it onto the exact logical size
      const [w, h] = TOWER_ASSETS[asset.key].content;
      const lw = Math.max(4, Math.round(w / 60));
      g.fillStyle(0xd8b98a, 1);
      g.fillRoundedRect(0, 0, w, h, 10);
      g.lineStyle(lw, 0x8a5a2b, 1);
      g.strokeRoundedRect(lw, lw, w - lw * 2, h - lw * 2, 10);
      g.generateTexture(key, w, h);
      g.destroy();
      return;
    }
    const map = {
      wood: [COLORS.WOOD, COLORS.WOOD_DARK], stone: [COLORS.STONE, COLORS.STONE_DARK],
      glass: [COLORS.GLASS, COLORS.GLASS_DARK], boom: [COLORS.BOOM, 0x8a3a24],
      pig: [0xf4a9b8, 0xc97b8f]
    };
    const mat = key.includes('stone') ? 'stone' : key.includes('glass') ? 'glass'
      : key.includes('tnt') || key.includes('boom') ? 'boom' : key.includes('pig') ? 'pig' : 'wood';
    const [fill, edge] = map[mat];
    g.fillStyle(fill, 1);
    g.fillRect(0, 0, 64, 64);
    g.lineStyle(4, edge, 1);
    g.strokeRect(2, 2, 60, 60);
    g.generateTexture(key, 64, 64);
    g.destroy();
  }

  blockTexture(g, key, fill, edge, alpha = 1) {
    g.clear();
    g.fillStyle(fill, alpha);
    g.fillRect(0, 0, 64, 64);
    g.lineStyle(4, edge, 1);
    g.strokeRect(2, 2, 60, 60);
    if (key === 'tex-wood') {
      g.lineStyle(2, edge, 0.6);
      for (let i = 1; i < 4; i++) {
        g.beginPath();
        g.moveTo(6, i * 16);
        g.lineTo(58, i * 16);
        g.strokePath();
      }
    } else if (key === 'tex-glass') {
      g.lineStyle(3, 0xffffff, 0.7);
      g.beginPath();
      g.moveTo(8, 52);
      g.lineTo(48, 10);
      g.strokePath();
    } else if (key === 'tex-stone') {
      g.fillStyle(edge, 0.5);
      g.fillRect(10, 12, 12, 10);
      g.fillRect(40, 30, 14, 12);
      g.fillRect(16, 44, 10, 8);
    }
    g.generateTexture(key, 64, 64);
  }

  circleTexture(g, key, color) {
    g.clear();
    g.fillStyle(color, 1);
    g.fillCircle(20, 20, 18);
    g.fillStyle(0xffffff, 0.45);
    g.fillCircle(14, 13, 6);
    g.generateTexture(key, 40, 40);
  }
}
